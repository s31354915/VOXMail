package speech

import (
	"html"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf8"
)

var (
	garbageRE      = regexp.MustCompile(`(?is)<(?:script|style|head)[^>]*>.*?</(?:script|style|head)>`)
	anchorRE       = regexp.MustCompile(`(?is)<a[^>]*href=["'][^"']+["'][^>]*>(.*?)</a>`)
	tagRE          = regexp.MustCompile(`(?is)<[^>]+>`)
	spaceRE        = regexp.MustCompile(`[ \t\r\n]+`)
	urlRE          = regexp.MustCompile(`(?i)\bhttps?://[^\s<>]+`)
	emailRE        = regexp.MustCompile(`(?i)\b[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}\b`)
	percentRE      = regexp.MustCompile(`\b(\d+(?:\.\d+)?)%`)
	currencyRE     = regexp.MustCompile(`([$€££])\s?(\d+(?:[.,]\d{1,2})?)`)
	phoneRE        = regexp.MustCompile(`(?:\+?\d[\d .()\-]{6,}\d)`)
	blockRE        = regexp.MustCompile(`(?is)</?(?:p|div|br|li|ul|ol|h[1-6]|tr|td|th|table|blockquote|pre)\b[^>]*>`)
	periodRunRE    = regexp.MustCompile(`(?:\.\s*){2,}`)
	leadingPunctRE = regexp.MustCompile(`^(?:\.\s*)+`)
	isoDateRE      = regexp.MustCompile(`\b(\d{4})-(\d{1,2})-(\d{1,2})\b`)
	slashDateRE    = regexp.MustCompile(`\b(\d{1,2})/(\d{1,2})/(\d{4})\b`)
	// Plain-text paragraph structure: quoted-reply markers are stripped,
	// blank-line breaks become sentence breaks, and single hard-wrapped
	// newlines become spaces.
	quoteMarkerRE    = regexp.MustCompile(`(?m)^[ \t]*>[ \t]?`)
	paragraphBreakRE = regexp.MustCompile(`[ \t\r]*\n[ \t\r]*\n+[ \t\r]*`)
	lineBreakRE      = regexp.MustCompile(`[ \t\r]*\r?\n[ \t\r]*`)
	// Cleans a sentence break inserted straight after a comma ("text,. "),
	// which paragraph and block handling can otherwise leave behind.
	commaPeriodRE = regexp.MustCompile(`([,;:])\s*\.\s*`)
	// Numbers: counts, figures, decimals, and clock times become English
	// words so Piper reads them as speech instead of unclear digit strings.
	commaNumberRE  = regexp.MustCompile(`\b\d{1,3}(?:,\d{3})+\b`)
	dottedNumberRE = regexp.MustCompile(`\b\d+(?:\.\d+)+\b`)
	clockTimeRE    = regexp.MustCompile(`\b(\d{1,2}):(\d{2})(?:\s*([AaPp])\.?[Mm]\.?)?\b`)
	// Two to seven digits: short counts and figures become words. Single
	// digits and long digit runs (tracking numbers, which phone handling
	// already spells digit by digit) stay as digits.
	integerRE = regexp.MustCompile(`\b\d{2,7}\b`)
)

// monthNames are used to speak calendar dates naturally instead of spelling
// every digit of a date stamp one by one.
var monthNames = [...]string{
	"January", "February", "March", "April", "May", "June",
	"July", "August", "September", "October", "November", "December",
}

// SpeechNormalizationVersion is part of every synthesized-prompt cache key.
// Increment it whenever the text sent to Piper changes without the source
// prompt itself changing, so a deployment cannot reuse audio generated by an
// older pronunciation policy.
const SpeechNormalizationVersion = 4

var speechTokenReplacements = []struct {
	pattern *regexp.Regexp
	text    string
}{
	// Brand and ordinary words must not be handed to Piper as mixed-case or
	// all-capital tokens: espeak-ng commonly interprets those as letter names.
	{regexp.MustCompile(`(?i)\bvox\s*mail\b`), "Vox Mail"},
	{regexp.MustCompile(`(?i)\bpin\b`), "pin"},
	{regexp.MustCompile(`(?i)\bsip\b`), "sip"},
	{regexp.MustCompile(`(?i)\bimap\b`), "eye map"},

	// These are genuine initialisms. Keep their spoken letters explicit so
	// Piper does not collapse them into an unrelated word.
	{regexp.MustCompile(`(?i)\bhttps\b`), "H T T P S"},
	{regexp.MustCompile(`(?i)\bhttp\b`), "H T T P"},
	{regexp.MustCompile(`(?i)\bsmtp\b`), "S M T P"},
	{regexp.MustCompile(`(?i)\bdtmf\b`), "D T M F"},
	{regexp.MustCompile(`(?i)\bivr\b`), "I V R"},
	{regexp.MustCompile(`(?i)\btotp\b`), "T O T P"},
	{regexp.MustCompile(`(?i)\bapi\b`), "A P I"},
	{regexp.MustCompile(`(?i)\burl\b`), "U R L"},
	{regexp.MustCompile(`(?i)\buuid\b`), "U U I D"},
	{regexp.MustCompile(`(?i)\buidvalidity\b`), "U I D validity"},
	{regexp.MustCompile(`(?i)\buid\b`), "U I D"},
	{regexp.MustCompile(`(?i)\bid\b`), "I D"},
	{regexp.MustCompile(`(?i)\btcp\b`), "T C P"},
	{regexp.MustCompile(`(?i)\budp\b`), "U D P"},
	{regexp.MustCompile(`(?i)\btls\b`), "T L S"},
	{regexp.MustCompile(`(?i)\brtp\b`), "R T P"},
	{regexp.MustCompile(`(?i)\bpcm\b`), "P C M"},
	{regexp.MustCompile(`(?i)\bwav\b`), "W A V"},
	{regexp.MustCompile(`(?i)\bstt\b`), "S T T"},
	{regexp.MustCompile(`(?i)\btts\b`), "T T S"},
	{regexp.MustCompile(`(?i)\bdns\b`), "D N S"},
}

// NormalizeForSpeech converts application text into pronunciation-friendly
// plain text immediately before it reaches Piper. It is deliberately a
// conservative vocabulary, rather than a rule that spells every capitalized
// word: all-caps email prose such as "IMPORTANT" must remain a word.
//
// EmailToSpeech runs first so URLs and addresses are expanded before tokens
// such as HTTP are considered. The operation is idempotent, which matters
// because email bodies may already have passed through EmailToSpeech.
func NormalizeForSpeech(input string) string {
	input = EmailToSpeech(input)
	for _, replacement := range speechTokenReplacements {
		input = replacement.pattern.ReplaceAllString(input, replacement.text)
	}
	return strings.TrimSpace(spaceRE.ReplaceAllString(input, " "))
}

// EmailToSpeech converts common technical tokens to words without exposing
// raw tracking URLs. It deliberately remains deterministic and local.
func EmailToSpeech(input string) string {
	input = html.UnescapeString(input)
	input = garbageRE.ReplaceAllString(input, " ")
	// Block-level tags are paragraph boundaries: they become sentence breaks
	// so Piper reads formatted email with natural pauses instead of as one
	// run-on line.
	input = blockRE.ReplaceAllString(input, ". ")
	input = anchorRE.ReplaceAllString(input, "link $1")
	input = tagRE.ReplaceAllString(input, " ")
	// Plain-text paragraphs: a blank line is a sentence break and a single
	// hard-wrapped newline is a space, so Piper reads paragraphs with pauses
	// instead of one run-on line. Quote markers are stripped first so they
	// do not leak into the speech.
	input = quoteMarkerRE.ReplaceAllString(input, "")
	input = paragraphBreakRE.ReplaceAllString(input, ". ")
	input = lineBreakRE.ReplaceAllString(input, " ")
	input = urlRE.ReplaceAllString(input, " link ")
	input = emailRE.ReplaceAllStringFunc(input, spellEmail)
	input = percentRE.ReplaceAllString(input, `$1 percent`)
	input = currencyRE.ReplaceAllStringFunc(input, speakCurrency)
	input = isoDateRE.ReplaceAllStringFunc(input, speakISODayMonthYear)
	input = slashDateRE.ReplaceAllStringFunc(input, speakSlashDayMonthYear)
	input = phoneRE.ReplaceAllStringFunc(input, groupDigits)
	input = commaNumberRE.ReplaceAllStringFunc(input, speakCommaNumber)
	input = dottedNumberRE.ReplaceAllStringFunc(input, speakDottedNumber)
	input = clockTimeRE.ReplaceAllStringFunc(input, speakClockTime)
	input = integerRE.ReplaceAllStringFunc(input, speakInteger)
	input = periodRunRE.ReplaceAllString(input, ". ")
	input = commaPeriodRE.ReplaceAllString(input, "$1 ")
	input = leadingPunctRE.ReplaceAllString(input, "")
	input = spaceRE.ReplaceAllString(input, " ")
	return strings.TrimSpace(input)
}

func speakISODayMonthYear(raw string) string {
	parts := isoDateRE.FindStringSubmatch(raw)
	return speakDateParts(parts[3], parts[2], parts[1])
}

func speakSlashDayMonthYear(raw string) string {
	parts := slashDateRE.FindStringSubmatch(raw)
	return speakDateParts(parts[2], parts[1], parts[3])
}

// speakDateParts joins day, month, and year as "October 17, 2026" when the
// values form a plausible calendar date; otherwise the raw text is kept.
func speakDateParts(dayText, monthText, yearText string) string {
	day, dayErr := strconv.Atoi(dayText)
	month, monthErr := strconv.Atoi(monthText)
	year, yearErr := strconv.Atoi(yearText)
	if dayErr != nil || monthErr != nil || yearErr != nil || month < 1 || month > 12 || day < 1 || day > 31 || year < 1900 || year > 2200 {
		return ""
	}
	return monthNames[month-1] + " " + dayText + ", " + strconv.Itoa(year)
}

var numberSmall = [...]string{
	"zero", "one", "two", "three", "four", "five", "six", "seven", "eight",
	"nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen",
	"sixteen", "seventeen", "eighteen", "nineteen",
}

var numberTens = [...]string{
	"", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy",
	"eighty", "ninety",
}

var numberScales = []struct {
	value int64
	name  string
}{
	{1000000000, "billion"},
	{1000000, "million"},
	{1000, "thousand"},
}

func speakInteger(raw string) string {
	value, err := strconv.ParseInt(raw, 10, 64)
	if err != nil {
		return raw
	}
	return intToWords(value)
}

func speakCommaNumber(raw string) string {
	return intToWords(parseDigits(strings.ReplaceAll(raw, ",", "")))
}

func speakDottedNumber(raw string) string {
	segments := strings.Split(raw, ".")
	if len(segments) != 2 {
		// Multi-part dotted numbers such as version strings (2.3.4) stay as
		// written; Piper reads them acceptably.
		return raw
	}
	words := []string{intToWords(parseDigits(segments[0])), "point"}
	for _, digit := range segments[1] {
		if digit >= '0' && digit <= '9' {
			words = append(words, numberSmall[digit-'0'])
		}
	}
	return strings.Join(words, " ")
}

func speakClockTime(raw string) string {
	parts := clockTimeRE.FindStringSubmatch(raw)
	if parts == nil {
		return raw
	}
	hour := parseDigits(parts[1])
	minute := parts[2]
	words := []string{intToWords(int64(hour))}
	switch {
	case minute == "00":
		// "3:00" stays "three"; adding "o'clock" risks Piper mangling it.
	case minute[0] == '0':
		words = append(words, "oh", numberSmall[minute[1]-'0'])
	default:
		words = append(words, intToWords(int64(parseDigits(minute))))
	}
	if parts[3] != "" {
		words = append(words, strings.ToLower(parts[3]), "m")
	}
	return strings.Join(words, " ")
}

func parseDigits(raw string) int64 {
	value, err := strconv.ParseInt(raw, 10, 64)
	if err != nil {
		return 0
	}
	return value
}

// intToWords spells an integer the way a person reads a count aloud:
// 6125 becomes "six thousand one hundred twenty five".
func intToWords(value int64) string {
	if value == 0 {
		return "zero"
	}
	if value < 0 {
		return "minus " + intToWords(-value)
	}
	var parts []string
	for _, scale := range numberScales {
		if value >= scale.value {
			parts = append(parts, threeDigitWords(int(value/scale.value)), scale.name)
			value %= scale.value
		}
	}
	if value > 0 {
		parts = append(parts, threeDigitWords(int(value)))
	}
	return strings.Join(parts, " ")
}

func threeDigitWords(value int) string {
	var parts []string
	if value >= 100 {
		parts = append(parts, numberSmall[value/100], "hundred")
		value %= 100
	}
	if value >= 20 {
		words := numberTens[value/10]
		if value%10 > 0 {
			words += "-" + numberSmall[value%10]
		}
		parts = append(parts, words)
	} else if value > 0 {
		parts = append(parts, numberSmall[value])
	}
	return strings.Join(parts, " ")
}

func spellEmail(value string) string {
	value = strings.ToLower(value)
	value = strings.ReplaceAll(value, "@", " at ")
	value = strings.ReplaceAll(value, ".", " dot ")
	value = strings.ReplaceAll(value, "-", " dash ")
	value = strings.ReplaceAll(value, "_", " underscore ")
	return value
}

func speakCurrency(raw string) string {
	kind := map[string]string{"$": "dollars", "€": "euros", "£": "pounds"}
	symbol, width := "", 0
	if first, size := utf8.DecodeRuneInString(raw); first != utf8.RuneError || size > 1 {
		symbol, width = string(first), size
	}
	if width == 0 {
		return raw
	}
	body := raw[width:]
	if i := strings.IndexAny(body, ".,"); i >= 0 {
		major := strings.ReplaceAll(body[:i], ",", " ")
		minor := strings.TrimLeft(body[i+1:], "0")
		if minor == "" {
			return major + " " + kind[symbol]
		}
		return major + " " + kind[symbol] + " and " + minor + " cents"
	}
	return strings.ReplaceAll(body, ",", " ") + " " + kind[symbol]
}

func groupDigits(value string) string {
	var b strings.Builder
	for _, r := range value {
		if r >= '0' && r <= '9' {
			b.WriteRune(r)
			b.WriteByte(' ')
		} else if r == '+' {
			b.WriteString(" plus ")
		}
	}
	return b.String()
}
