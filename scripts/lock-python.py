#!/usr/bin/env python3
"""Resolve runtime wheels for Python 3.11/glibc 2.36 on both image targets.

Run inside the Dockerfile's pinned Python base. This script deliberately requires
that interpreter: pip's cross-platform flags do not replace all marker values.
The resulting lock freezes versions and approved wheel hashes; reviewers must
inspect its diff and rerun hashed wheel/install/runtime acceptance before use.
"""

import argparse
import json
import pathlib
import subprocess
import sys
import tempfile

from pip._vendor.packaging.markers import default_environment
from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name, parse_wheel_filename
from pip._vendor.packaging.version import Version


def resolve(report_path, requirements, machine):
    platforms = []
    for glibc in range(36, 16, -1):
        platforms.extend(["--platform", f"manylinux_2_{glibc}_{machine}"])
    platforms.extend(["--platform", f"manylinux2014_{machine}"])
    command = [sys.executable, "-m", "pip", "install", "--dry-run",
               "--ignore-installed", "--only-binary=:all:", "--disable-pip-version-check",
               "--index-url", "https://pypi.org/simple", "--report", str(report_path),
               "--python-version", "3.11", "--implementation", "cp",
               "--abi", "cp311", "--abi", "abi3", "--abi", "none", *platforms,
               "--requirement", str(requirements)]
    subprocess.run(command, check=True)
    report = json.loads(report_path.read_text())
    packages = {canonicalize_name(item["metadata"]["name"]): item for item in report["install"]}
    # Verify dependencies against the actual target environment, including
    # architecture markers, rather than trusting the cross-platform resolver.
    environment = default_environment()
    environment.update(platform_machine=machine, sys_platform="linux", extra="")
    for name, item in packages.items():
        for dependency in item["metadata"].get("requires_dist", []):
            requirement = Requirement(dependency)
            if requirement.marker and not requirement.marker.evaluate(environment):
                continue
            target = packages.get(canonicalize_name(requirement.name))
            if target is None or not requirement.specifier.contains(target["metadata"]["version"]):
                raise RuntimeError(f"{machine}: unresolved dependency {name}: {dependency}")
        wheel = pathlib.PurePosixPath(item["download_info"]["url"]).name
        wheel_name, wheel_version, _, _ = parse_wheel_filename(wheel)
        if canonicalize_name(wheel_name) != name or wheel_version != Version(item["metadata"]["version"]):
            raise RuntimeError(f"{machine}: unexpected wheel identity {wheel}")
    return packages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=pathlib.Path, default=pathlib.Path("requirements/python.in"))
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("requirements/python.lock"))
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 11):
        parser.error("use the pinned Dockerfile Python 3.11 base, not the host interpreter")
    with tempfile.TemporaryDirectory(prefix="voxmail-python-lock-") as tmp:
        tmp = pathlib.Path(tmp)
        amd = resolve(tmp / "amd64.json", args.input, "x86_64")
        exact = tmp / "exact.in"
        exact.write_text("".join(f'{name}=={item["metadata"]["version"]}\n' for name, item in sorted(amd.items())))
        arm = resolve(tmp / "arm64.json", exact, "aarch64")
        if set(amd) != set(arm):
            raise RuntimeError("target dependency sets differ; add explicit reviewed markers")
        lines = ["# Generated by scripts/lock-python.py in the pinned Python 3.11 base.",
                 "# CPython 3.11, Linux glibc 2.36 targets: amd64 and arm64. Wheels only.",
                 "# Update requirements/python.in, regenerate, and review versions/hashes.", ""]
        for name, item in sorted(amd.items()):
            version = item["metadata"]["version"]
            if arm[name]["metadata"]["version"] != version:
                raise RuntimeError(f"architecture version mismatch: {name}")
            hashes = sorted({target[name]["download_info"]["archive_info"]["hashes"]["sha256"] for target in (amd, arm)})
            lines.append(f"{name}=={version} \\")
            for i, digest in enumerate(hashes):
                if len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
                    raise RuntimeError(f"invalid wheel hash: {name}")
                lines.append("    --hash=sha256:" + digest + (" \\" if i + 1 < len(hashes) else ""))
        args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
